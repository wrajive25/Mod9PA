#File-Reading Function
def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row
    with open("PalmerPenguins.csv", "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row

#Function to calcuate species percentages
def calculate_percentage(count, total):
    return (count/total) * 100

#Function to classify species
def classify_species(species_percentages):
    if species_percentages < 25:
       category = "small"
    elif (species_percentages >= 25) and (species_percentages < 40):
       category = "medium"
    else:
       category = "large"
    return category

#Function to determine position
def get_position_description(selected_species, largest_species,
                             smallest_species):
    if (selected_species == largest_species):
        size = "largest"
    elif (selected_species == smallest_species):
        size = "smallest"
    else:
        size = "middle-sized"
    return size

#Function to display species statistics
